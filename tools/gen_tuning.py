#!/usr/bin/env python3
"""Generates src/core/TuningParams.hpp from data/gameplay.json.

gameplay.json is the single source of truth: its structure defines the C++ `Tuning` struct, its
values become the member defaults, and each knob's trailing `// comment` becomes its documentation
(shown by `labyterm --tuning`). Rerun after adding/removing/renaming a knob:

    python3 tools/gen_tuning.py            # from the LabyTerm root

Type rules: integer literal -> int, decimal literal -> double, an object whose keys are all stat
names (STR..CHA) -> StatTable, an object keyed by monster class whose values are stat objects ->
ClassStatTable.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "gameplay.json")
OUT = os.path.join(ROOT, "src", "core", "TuningParams.hpp")
STATS = ["STR", "DEX", "INT", "VIT", "CHA"]
CLASSES = ["HUMAN", "UNDEAD", "ANIMAL", "DEMON", "FAE"]


def strip_comments(text):
    """Remove // and /* */ comments that are outside strings."""
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\":
                out.append(text[i + 1]); i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True; out.append(c)
        elif text.startswith("//", i):
            while i < n and text[i] != "\n": i += 1
            continue
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 2
            continue
        else:
            out.append(c)
        i += 1
    return "".join(out)


def collect_docs(text):
    """path -> trailing comment, by scanning one-knob-per-line layout."""
    docs, stack = {}, []
    leaf = re.compile(r'^"(\w+)"\s*:\s*(.*?)\s*(?://\s*(.*))?$')
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("//") or line == "{":
            continue
        if re.match(r"^\}\s*,?\s*(//.*)?$", line):
            if stack: stack.pop()
            continue
        m = leaf.match(line)
        if not m:
            continue
        key, value, doc = m.group(1), m.group(2).rstrip(","), (m.group(3) or "").strip()
        if value.startswith("{") and not value.endswith("}"):
            stack.append(key)              # group opener: `"name": {   // optional doc`
            if doc: docs[".".join(stack)] = doc
        elif doc:
            docs[".".join(stack + [key])] = doc
    return docs


def kind_of(v):
    if isinstance(v, bool): raise SystemExit("booleans are not supported as tuning values")
    if isinstance(v, int): return "int"
    if isinstance(v, float): return "double"
    if isinstance(v, dict):
        if v and all(k in STATS for k in v): return "StatTable"
        if v and all(k in CLASSES for k in v) and all(isinstance(x, dict) for x in v.values()):
            return "ClassStatTable"
        return "group"
    raise SystemExit(f"unsupported value {v!r}")


def cpp_double(x):
    s = repr(float(x))
    return s if any(ch in s for ch in ".en") else s + ".0"


def stat_init(d):
    vals = [cpp_double(d.get(k, 0)) for k in STATS]
    return "{{" + ", ".join(vals) + "}}"


def pascal(name):
    return name[0].upper() + name[1:]


def main():
    text = open(SRC, encoding="utf-8").read()
    data = json.loads(strip_comments(text))
    docs = collect_docs(text)
    missing = []
    params = []                     # (path, kind)
    structs = []

    for gname, group in data.items():
        if kind_of(group) != "group":
            raise SystemExit(f"top-level '{gname}' must be a group of knobs")
        lines = [f"  struct {pascal(gname)} {{"]
        for key, v in group.items():
            k, path = kind_of(v), f"{gname}.{key}"
            if k == "group":
                raise SystemExit(f"{path}: nested groups are not supported (only stat tables)")
            doc = docs.get(path, "")
            if not doc:
                missing.append(path)
            if k == "int":
                lines.append(f"    int {key} = {v};")
            elif k == "double":
                lines.append(f"    double {key} = {cpp_double(v)};")
            elif k == "StatTable":
                lines.append(f"    StatTable {key} = {stat_init(v)};")
            else:
                inner = ", ".join(stat_init(v.get(c, {})) for c in CLASSES)
                lines.append(f"    ClassStatTable {key} = {{{{{inner}}}}};")
            params.append((path, k))
        lines.append("  };")
        lines.append(f"  {pascal(gname)} {gname};")
        structs.append("\n".join(lines))

    if missing:
        raise SystemExit("knobs missing a trailing '// doc' comment on their line:\n  " + "\n  ".join(missing))

    out = []
    w = out.append
    w("// GENERATED by tools/gen_tuning.py from data/gameplay.json. DO NOT EDIT; rerun the tool.")
    w("// Defaults here mirror gameplay.json; the file is authoritative at runtime (see Tuning.cpp).")
    w("#pragma once")
    w("#include <array>")
    w("#include <string_view>")
    w("")
    w('#include "core/Enums.hpp"')
    w("")
    w("namespace laby {")
    w("")
    w("// One value per stat, indexed by Stat (0 = unspecified)")
    w("using StatTable = std::array<double, kStatCount>;")
    w("// One StatTable per monster class, indexed by MonsterClass")
    w("using ClassStatTable = std::array<StatTable, kMonsterClassCount>;")
    w("")
    w("struct Tuning {")
    w("\n\n".join(structs))
    w("};")
    w("")
    w(f"inline constexpr int kTuningParamCount = {len(params)};")
    w("")
    w("// Calls f(path, field) for every knob, e.g. f(\"combat.baseToHit\", t.combat.baseToHit).")
    w("template <class F>")
    w("void forEachParam(Tuning& t, F&& f) {")
    for path, _ in params:
        w(f'  f("{path}", t.{path});')
    w("}")
    w("")
    w("struct ParamDoc { std::string_view path; std::string_view doc; };")
    w(f"inline constexpr std::array<ParamDoc, {len(params)}> kTuningDocs = {{{{")
    for path, _ in params:
        d = docs[path].replace("\\", "\\\\").replace('"', '\\"')
        w(f'    {{"{path}", "{d}"}},')
    w("}};")
    w("")
    w("}  // namespace laby")
    new = "\n".join(out) + "\n"
    old = open(OUT).read() if os.path.exists(OUT) else None
    if old != new:
        open(OUT, "w").write(new)
    print(f"{'wrote' if old != new else 'unchanged'} {os.path.relpath(OUT, ROOT)} ({len(params)} knobs in {len(structs)} groups)")


main()
