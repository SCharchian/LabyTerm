#!/usr/bin/env python3
"""Generates src/render/TermGlyphs.hpp: the real Unicode character for each 2x4 octant pattern.

The game's mosaic glyphs are private-use codepoints (GlyphAtlas.hpp: bit i = column i%2, row i/2). A terminal has
no such glyphs, so it needs the standard Unicode 16 "octant" characters. Unicode encodes only 230 of the 256
patterns as BLOCK OCTANT-<cells>; the other 26 already existed elsewhere (quadrants, quarter blocks, ...).
Needs Python >= 3.13 (Unicode 16 names). Run: python3 -I tools/gen_term_glyphs.py
"""
import unicodedata

assert unicodedata.unidata_version >= "16", "needs Python 3.13+ (Unicode 16 names)"

def cells_mask(cells):  # octant cell numbers 1..8 (row-major, 1 = top-left) -> pattern bits
    return sum(1 << (int(c) - 1) for c in cells)

table = {0: 0x20}
for cp in range(0x1CD00, 0x1CE00):
    n = unicodedata.name(chr(cp), "")
    if n.startswith("BLOCK OCTANT-"):
        table[cells_mask(n.removeprefix("BLOCK OCTANT-"))] = cp

# Patterns that Unicode encoded before octants existed, found by name so a wrong codepoint cannot slip in.
UL, UR, LL, LR = 0b00000101, 0b00001010, 0b01010000, 0b10100000  # quadrants as octant patterns
named = {
    "FULL BLOCK": 0xFF,
    "UPPER HALF BLOCK": UL | UR, "LOWER HALF BLOCK": LL | LR,
    "LEFT HALF BLOCK": UL | LL, "RIGHT HALF BLOCK": UR | LR,
    "QUADRANT UPPER LEFT": UL, "QUADRANT UPPER RIGHT": UR,
    "QUADRANT LOWER LEFT": LL, "QUADRANT LOWER RIGHT": LR,
    "QUADRANT UPPER LEFT AND LOWER RIGHT": UL | LR, "QUADRANT UPPER RIGHT AND LOWER LEFT": UR | LL,
    "QUADRANT UPPER LEFT AND UPPER RIGHT AND LOWER LEFT": UL | UR | LL,
    "QUADRANT UPPER LEFT AND UPPER RIGHT AND LOWER RIGHT": UL | UR | LR,
    "QUADRANT UPPER LEFT AND LOWER LEFT AND LOWER RIGHT": UL | LL | LR,
    "QUADRANT UPPER RIGHT AND LOWER LEFT AND LOWER RIGHT": UR | LL | LR,
    "UPPER ONE QUARTER BLOCK": 0b00000011, "UPPER THREE QUARTERS BLOCK": 0b00111111,
    "LOWER ONE QUARTER BLOCK": 0b11000000, "LOWER THREE QUARTERS BLOCK": 0b11111100,
    "MIDDLE LEFT ONE QUARTER BLOCK": 0b00010100, "MIDDLE RIGHT ONE QUARTER BLOCK": 0b00101000,
    "LEFT HALF UPPER ONE QUARTER BLOCK": 0b00000001, "RIGHT HALF UPPER ONE QUARTER BLOCK": 0b00000010,
    "LEFT HALF LOWER ONE QUARTER BLOCK": 0b01000000, "RIGHT HALF LOWER ONE QUARTER BLOCK": 0b10000000,
}
for name, pat in named.items():
    cp = unicodedata.lookup(name)
    assert pat not in table, (name, pat)
    table[pat] = ord(cp)

missing = [p for p in range(256) if p not in table]
assert not missing, f"patterns without a character: {missing}"
octants = sum(1 for cp in table.values() if 0x1CD00 <= cp < 0x1CE00)
assert octants == 230, octants

rows = []
for i in range(0, 256, 4):
    rows.append("    " + ", ".join(f"0x{table[p]:X}" for p in range(i, i + 4)) + ",")
open("src/render/TermGlyphs.hpp", "w").write(
    "#pragma once\n// Generated by tools/gen_term_glyphs.py: do not edit.\n#include <cstdint>\n\nnamespace laby {\n\n"
    "// The standard Unicode character for each 2x4 octant pattern (GlyphAtlas.hpp bit order). Patterns that are\n"
    "// quadrants, quarter blocks or empty/full use the older block characters; the other 230 are U+1CD00..U+1CDE5.\n"
    "inline constexpr char32_t kOctantChar[256] = {\n" + "\n".join(rows) + "\n};\n\n}  // namespace laby\n")
print("wrote src/render/TermGlyphs.hpp")
